"""Reporting: the human-readable per-panel verdict, BEST_CONFIG.md, and the
comparison against earlier runs."""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd

from search import runlog
from search._project_root import PROJECT_ROOT
from search.sweep.audit import overfit_verdict
from search.sweep.config import GAP_LIMIT, OBJECTIVES, SELECT_OBJECTIVE, STABILITY_MIN, SWEEP_PROFILE


def report_panel(panel, all_df, win, fallback):
    """Print the panel's decision to the console in human-readable form."""
    passed = int(all_df["passes"].sum())
    ok, fails, warns = overfit_verdict(win)
    print()
    print("  " + "=" * 74)
    print(f"  * {panel} — SELECTED CONFIGURATION")
    print("  " + "=" * 74)
    print(f"    Feature selection    : {win['selection']}   ({win['n_features']} features)")
    print(f"    Data augmentation    : " +
          (f"from GENEL, ratio {win['aug_frac']:g}" if win["aug_frac"] > 0 else "none"))
    print(f"    Diverse view         : {'on' if win['diverse'] else 'off'}")
    print(f"    Candidate pool       : {win['pool']}"
          f"   ({'single+mean+stack' if win['pool']=='all' else 'single models only'})")
    print(f"    Champion selection rule: {win['rule']} One-SE")
    print(f"    SELECTED MODEL       : {win['champion']}  ({win['strategy']})")
    print(f"    DECISION THRESHOLD   : {win['threshold']:.3f}   "
          f"(policy: {win['policy']})")
    print()
    print(f"    -- PERFORMANCE --")
    print(f"    Honest (nested) F1   : {win['honest_f1']:.4f} +/- {win['honest_f1_std']:.4f}"
          f"   <- THE NUMBER TO TRUST")
    print(f"    Honest balanced F1   : {win['honest_balanced_f1']:.4f}   (if test is 1:1)")
    print(f"    Honest ROC-AUC       : {win['honest_auc']:.4f}")
    print(f"    OOF F1 (optimistic)  : {win['oof_f1']:.4f}")
    print(f"    Naive baseline F1    : {win['trivial_f1']:.4f}   "
          f"(gain {win['honest_f1']-win['trivial_f1']:+.4f})")
    print(f"    Confusion matrix     : TN={win['tn']} FP={win['fp']} "
          f"FN={win['fn']} TP={win['tp']}")
    print()
    print(f"    -- OVERFITTING AUDIT --")
    g = "PASSED" if win["gap"] <= GAP_LIMIT else "FAILED"
    s = "PASSED" if win["stability"] >= STABILITY_MIN else "FAILED"
    b = "PASSED" if win["honest_f1"] > win["trivial_f1"] else "FAILED"
    print(f"    1) Optimism gap        : {win['gap']:+.4f}  (limit {GAP_LIMIT:.3f})"
          f"        -> {g}")
    print(f"    2) Champion stability  : %{100*win['stability']:.0f} of outer folds picked the same candidate"
          f"  (limit %{100*STABILITY_MIN:.0f})  -> {s}")
    print(f"    3) Beats naive baseline: {win['honest_f1']:.4f} > {win['trivial_f1']:.4f}"
          f"          -> {b}")
    if warns:
        for w in warns:
            print(f"    ! warning: {w}")
    if fallback:
        print(f"    x RESULT: NO configuration passed the audit — the one with the "
              f"smallest deviation was picked.\n         Treat this panel's result WITH CAUTION.")
    elif ok:
        print(f"    v RESULT: NO SIGN OF OVERFITTING")
    print()
    print(f"    -- WHY THIS ONE? --")
    print(f"    {len(all_df)} configurations were tried; {passed} passed the "
          f"overfitting audit, {len(all_df)-passed} were eliminated.")
    print(f"    Selection objective: {SELECT_OBJECTIVE}"
          + ("  = min(honest F1, honest balanced F1)" if SELECT_OBJECTIVE == "robust" else ""))
    for obj in OBJECTIVES:
        pool = all_df[all_df["passes"]] if passed else all_df
        top = pool.sort_values(f"obj_{obj}", ascending=False).iloc[0]
        same = "  <- selected" if (top["rule"], top["pool"], top["policy"],
                                 top["selection"], top["aug_frac"]) == \
                                (win["rule"], win["pool"], win["policy"],
                                 win["selection"], win["aug_frac"]) else ""
        print(f"      {obj:<20s} best -> {top['champion']:<20s} "
              f"threshold {top['threshold']:.3f}  {top[f'obj_{obj}']:.4f}{same}")


def write_best_config_md(winners, all_rows, path):
    """Human-readable final decision file — meant to still make sense months later."""
    L = []
    A = L.append
    A("# BEST CONFIGURATION — final decision")
    A("")
    A(f"Generated on  : {datetime.now():%Y-%m-%d %H:%M}")
    A(f"Generated by  : `search.sweep`  (profile: `{SWEEP_PROFILE}`)")
    A(f"Selection objective : `{SELECT_OBJECTIVE}`"
      + ("  = min(honest F1, honest balanced F1) — test class ratio is unknown"
         if SELECT_OBJECTIVE == "robust" else ""))
    A(f"Overfitting limits : optimism gap <= {GAP_LIMIT:.3f} · "
      f"champion stability >= %{100*STABILITY_MIN:.0f} · honest F1 > naive baseline")
    A("")
    A("**Which number should I trust?** `Honest F1` comes from nested cross-validation: "
      "feature selection, model selection and the decision threshold are all determined "
      "using only the training rows of each outer fold, then measured once on the "
      "untouched test fold. OOF F1 is optimistic and is used for model selection; it "
      "is NOT a generalization estimate. See WARNING.md for a caveat about hyperparameters "
      "specifically (they are NOT re-tuned inside each outer fold).")
    A("")
    A("## Summary")
    A("")
    A("| Panel | Model | Threshold | Policy | Features | Augmentation | Honest F1 | Honest balanced F1 | Honest AUC | Gap | Stability | Overfitting |")
    A("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for p, w in winners.items():
        ok, fails, _ = overfit_verdict(w)
        A(f"| {p} | {w['champion']} | {w['threshold']:.3f} | {w['policy']} | "
          f"{w['selection']}/{w['n_features']} | {w['aug_frac']:g} | "
          f"**{w['honest_f1']:.4f}** | {w['honest_balanced_f1']:.4f} | "
          f"{w['honest_auc']:.4f} | {w['gap']:+.4f} | %{100*w['stability']:.0f} | "
          f"{'clean' if ok else 'RISKY'} |")
    A("")
    hf = np.mean([w["honest_f1"] for w in winners.values()])
    hb = np.mean([w["honest_balanced_f1"] for w in winners.values()])
    ha = np.mean([w["honest_auc"] for w in winners.values()])
    A(f"**Mean honest F1 = {hf:.4f}** · mean honest balanced F1 = {hb:.4f} · "
      f"mean honest AUC = {ha:.4f}")
    A("")
    for p, w in winners.items():
        ok, fails, warns = overfit_verdict(w)
        A(f"## {p}")
        A("")
        A("| Setting | Value |")
        A("|---|---|")
        A(f"| Feature selection | `{w['selection']}` ({w['n_features']} features) |")
        A(f"| Data augmentation | " +
          (f"from GENEL, ratio {w['aug_frac']:g}" if w["aug_frac"] > 0 else "none") + " |")
        A(f"| Diverse view (ReliefF) | {'on' if w['diverse'] else 'off'} |")
        A(f"| Candidate pool | `{w['pool']}` |")
        A(f"| Champion selection rule | `{w['rule']}` One-SE |")
        A(f"| **Selected model** | **{w['champion']}** ({w['strategy']}) |")
        A(f"| **Decision threshold** | **{w['threshold']:.3f}** (policy `{w['policy']}`) |")
        A(f"| Honest F1 | **{w['honest_f1']:.4f} +/- {w['honest_f1_std']:.4f}** |")
        A(f"| Honest balanced F1 (1:1) | {w['honest_balanced_f1']:.4f} |")
        A(f"| Honest ROC-AUC | {w['honest_auc']:.4f} |")
        A(f"| OOF F1 (optimistic) | {w['oof_f1']:.4f} |")
        A(f"| Naive baseline F1 | {w['trivial_f1']:.4f} |")
        A(f"| TN / FP / FN / TP | {w['tn']} / {w['fp']} / {w['fn']} / {w['tp']} |")
        A("")
        A("**Overfitting audit**")
        A("")
        A(f"- Optimism gap `{w['gap']:+.4f}` (limit {GAP_LIMIT:.3f}) — "
          f"{'PASSED' if w['gap'] <= GAP_LIMIT else 'FAILED'}")
        A(f"- Champion stability `%{100*w['stability']:.0f}` "
          f"({w['n_distinct_champions']} distinct winners, limit %{100*STABILITY_MIN:.0f}) — "
          f"{'PASSED' if w['stability'] >= STABILITY_MIN else 'FAILED'}")
        A(f"- Beats naive baseline — "
          f"{'PASSED' if w['honest_f1'] > w['trivial_f1'] else 'FAILED'}")
        for wr in warns:
            A(f"- ! {wr}")
        A("")
        A(f"**Verdict: {'NO SIGN OF OVERFITTING' if ok else 'RISKY — ' + '; '.join(fails)}**")
        A("")
        sub = all_rows[all_rows["panel"] == p]
        A(f"{len(sub)} configurations were tried on this panel, {int(sub['passes'].sum())} "
          f"passed the audit. Top 5 (among those that passed, by `{SELECT_OBJECTIVE}`):")
        A("")
        A("| # | selection | augmentation | rule | pool | policy | model | threshold | Honest F1 | Balanced F1 | Gap |")
        A("|---|---|---|---|---|---|---|---|---|---|---|")
        pool = sub[sub["passes"]] if sub["passes"].any() else sub
        for i, (_, r) in enumerate(pool.sort_values(f"obj_{SELECT_OBJECTIVE}",
                                                    ascending=False).head(5).iterrows(), 1):
            A(f"| {i} | {r['selection']} | {r['aug_frac']:g} | {r['rule']} | {r['pool']} | "
              f"{r['policy']} | {r['champion']} | {r['threshold']:.3f} | "
              f"{r['honest_f1']:.4f} | {r['honest_balanced_f1']:.4f} | {r['gap']:+.4f} |")
        A("")
    A("## How to use this bundle")
    A("")
    A("Each panel's winning model lives under `outputs_best/models/<PANEL>/`; "
      "`champion.json` carries the selected model, its threshold and all its settings. "
      "If every panel's champion is a single tuned XGBoost model, "
      "`outputs_best/champion_config.json` is also written in the format "
      "`pathugen/champion_config.py` reads — copy it over the project's own "
      "`champion_config.json` and run `python PatHUgen.py train` to adopt it "
      "(see `Champion_Config.md`). A panel whose champion is a mean/stack strategy "
      "is NOT included in that file, since `pathugen.train()` only knows how to fit "
      "a single XGBoost model — adopting such a result requires extending `pathugen` first.")
    A("")
    A("If the test set's class ratio turns out to differ from training, there is no "
      "need to retrain: `champion.json`'s `prior_shifted_thresholds` gives ready-made "
      "thresholds (over the isotonic-calibrated probabilities).")
    Path(path).write_text("\n".join(L), encoding="utf-8")


def compare_previous(winners):
    """Side-by-side with the reference and improved pipeline results, when available."""
    refs = {"reference": PROJECT_ROOT / "outputs_final" / "results_summary.csv",
            "improved": PROJECT_ROOT / "outputs_improved" / "results_summary_improved.csv",
            "PDR (Colab)": None}
    colab = None
    zpath = PROJECT_ROOT / "outputs_colab.zip"
    if zpath.exists():
        import zipfile
        try:
            with zipfile.ZipFile(zpath) as z:
                import io
                colab = pd.read_csv(io.BytesIO(
                    z.read("outputs_colab/results_summary.csv")))
        except Exception:
            colab = None

    runlog.section("COMPARISON WITH EARLIER RUNS (honest / nested F1)")
    rows = []
    for p, w in winners.items():
        row = {"panel": p, "search.sweep": round(w["honest_f1"], 4)}
        for label, path in refs.items():
            if path is None:
                continue
            if path.exists():
                d = pd.read_csv(path)
                m = d[d["panel"] == p]
                if not m.empty and "honest_f1" in d.columns:
                    row[label] = round(float(m.iloc[0]["honest_f1"]), 4)
        if colab is not None:
            m = colab[colab["panel"] == p]
            if not m.empty:
                row["PDR (Colab)"] = round(float(m.iloc[0]["honest_f1"]), 4)
        rows.append(row)
    t = pd.DataFrame(rows)
    print(t.to_string(index=False))
    for c in t.columns:
        if c in ("panel", "search.sweep"):
            continue
        d = (t["search.sweep"] - t[c]).mean()
        print(f"  search.sweep - {c:<22s} mean difference: {d:+.4f}")
    print("\nNote: only 'honest (nested) F1' is compared — OOF scores are optimistic "
          "and\nare not comparable across runs.")
